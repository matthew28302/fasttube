def clean_track_title(raw_title: str) -> str:
    """
    Cleans noisy metadata from YouTube titles (e.g. '[OFFICIAL MV]', '(Lyric Video)', '4K 60FPS')
    while preserving the core song name and featured artists.
    """
    if not raw_title:
        return ""
    t = raw_title.strip()
    # Remove bracketed junk: [OFFICIAL MV], (Official Music Video), [Lyric Video], etc.
    noise_patterns = [
        r"\[\s*(official\s*mv|official\s*music\s*video|official\s*video|official\s*audio|mv|video\s*lyric|audio|4k|hd|mv\s*hd)\s*\]",
        r"\(\s*(official\s*mv|official\s*music\s*video|official\s*video|official\s*audio|mv|video\s*lyric|audio|4k|hd|mv\s*hd)\s*\)",
        r"\|\s*(official\s*mv|official\s*music\s*video|official\s*video|official\s*audio)\s*",
        r"-\s*(official\s*mv|official\s*music\s*video|official\s*video)\s*",
    ]
    for p in noise_patterns:
        t = re.sub(p, " ", t, flags=re.IGNORECASE)
    # Collapse multiple spaces
    t = re.sub(r"\s+", " ", t).strip()
    return t or raw_title


def _parse_duration_str(dur_str: str) -> Optional[int]:
    """Parse '3:45' or '1:12:30' into total seconds."""
    if not dur_str:
        return None
    parts = dur_str.strip().split(":")
    try:
        if len(parts) == 2:
            return int(parts[0]) * 60 + int(parts[1])
        if len(parts) == 3:
            return int(parts[0]) * 3600 + int(parts[1]) * 60 + int(parts[2])
    except (ValueError, TypeError):
        return None
    return None


def get_youtube_mix_playlist(
    video_id: str,
    *,
    limit: int = 25,
    max_duration_s: int = 720,  # 12 minutes default (filters out 1-hour compilations/podcasts)
    hl: str = "vi",
    gl: str = "VN",
    timeout: int = 8,
) -> list[dict[str, Any]]:
    """
    Fetches YouTube's actual native algorithmic Mix/Radio for a seed video.
    This uses YouTube's 'RD{video_id}' playlist endpoint on Innertube,
    returning the exact curated sequence generated by YouTube's recommendation engine.
    """
    vid = (video_id or "").strip()
    if not vid:
        return []

    url = f"https://www.youtube.com/youtubei/v1/next?key={_INNERTUBE_KEY}"
    headers = {
        "User-Agent": _UA,
        "Content-Type": "application/json",
        "Origin": "https://www.youtube.com",
    }
    body = {
        "context": {
            "client": {
                "clientName": "WEB",
                "clientVersion": "2.20240101.00.00",
                "hl": hl,
                "gl": gl,
            }
        },
        "videoId": vid,
        "playlistId": f"RD{vid}",
    }

    try:
        r = _SESSION.post(url, headers=headers, json=body, timeout=timeout)
        if r.status_code != 200:
            logger.warning("YouTube Mix API returned status %s for video_id=%s", r.status_code, vid)
            return []
        data = r.json()
    except Exception as e:
        logger.warning("YouTube Mix API request failed for video_id=%s: %s", vid, e)
        return []

    playlist = (
        data.get("contents", {})
        .get("twoColumnWatchNextResults", {})
        .get("playlist", {})
        .get("playlist", {})
    )
    items = playlist.get("contents", [])
    if not items:
        return []

    raw_tracks: list[dict[str, Any]] = []
    seen_ids: set[str] = set()

    for it in items:
        pr = it.get("playlistPanelVideoRenderer")
        if not pr:
            continue
        v_id = pr.get("videoId")
        if not v_id or v_id in seen_ids:
            continue

        raw_title = pr.get("title", {}).get("simpleText") or "".join(
            x.get("text", "") for x in pr.get("title", {}).get("runs", [])
        ).strip()
        if not raw_title:
            continue

        author = pr.get("shortBylineText", {}).get("runs", [{}])[0].get("text", "").strip() or "YouTube"
        length_str = pr.get("lengthText", {}).get("simpleText", "").strip()
        dur_s = _parse_duration_str(length_str)

        # Filter out 1-hour compilations, DJ non-stop, or video podcasts (> 12 mins)
        if max_duration_s and dur_s is not None and dur_s > max_duration_s:
            continue

        thumbs = pr.get("thumbnail", {}).get("thumbnails", [])
        thumb = thumbs[-1]["url"] if thumbs else f"https://i.ytimg.com/vi/{v_id}/hqdefault.jpg"

        seen_ids.add(v_id)
        raw_tracks.append({
            "id": v_id,
            "title": clean_track_title(raw_title),
            "original_title": raw_title,
            "channel": author,
            "duration": length_str or "3:30",
            "duration_s": dur_s,
            "thumb": thumb,
            "stream_url": f"/stream/{v_id}",
        })

    # Apply YouTube's Pacing & Artist Separation Algorithm
    # (Prevents clustering: no single artist should play more than 2 songs consecutively)
    spaced_tracks = _apply_artist_spacing(raw_tracks, max_consecutive=2)
    return spaced_tracks[:limit]


def get_youtube_related_tracks(
    video_id: str,
    *,
    limit: int = 15,
    max_duration_s: int = 720,
    hl: str = "vi",
    gl: str = "VN",
    timeout: int = 8,
) -> list[dict[str, Any]]:
    """
    Fetches YouTube's 'Up Next' / 'Related' recommendations for a video.
    Parses both legacy compactVideoRenderer and modern lockupViewModel.
    """
    vid = (video_id or "").strip()
    if not vid:
        return []

    url = f"https://www.youtube.com/youtubei/v1/next?key={_INNERTUBE_KEY}"
    headers = {
        "User-Agent": _UA,
        "Content-Type": "application/json",
        "Origin": "https://www.youtube.com",
    }
    body = {
        "context": {
            "client": {
                "clientName": "WEB",
                "clientVersion": "2.20240101.00.00",
                "hl": hl,
                "gl": gl,
            }
        },
        "videoId": vid,
    }

    try:
        r = _SESSION.post(url, headers=headers, json=body, timeout=timeout)
        if r.status_code != 200:
            return []
        data = r.json()
    except Exception as e:
        logger.warning("YouTube Related API request failed for video_id=%s: %s", vid, e)
        return []

    results = (
        data.get("contents", {})
        .get("twoColumnWatchNextResults", {})
        .get("secondaryResults", {})
        .get("secondaryResults", {})
        .get("results", [])
    )

    tracks: list[dict[str, Any]] = []
    seen: set[str] = {vid}

    for it in results:
        v_id: Optional[str] = None
        title: str = ""
        channel: str = "YouTube"
        length_str: str = ""
        thumb: str = ""

        if "lockupViewModel" in it:
            m = it["lockupViewModel"]
            v_id = m.get("contentId")
            if not v_id or v_id in seen:
                continue
            # Title
            title = m.get("metadata", {}).get("lockupMetadataViewModel", {}).get("title", {}).get("content", "")
            # Author
            meta_rows = (
                m.get("metadata", {})
                .get("lockupMetadataViewModel", {})
                .get("metadata", {})
                .get("contentMetadataViewModel", {})
                .get("metadataRows", [])
            )
            for row in meta_rows:
                for part in row.get("metadataParts", []):
                    c = part.get("text", {}).get("content", "")
                    if c and not channel or channel == "YouTube":
                        channel = c
            # Thumbnail
            sources = m.get("contentImage", {}).get("thumbnailViewModel", {}).get("image", {}).get("sources", [])
            thumb = sources[-1]["url"] if sources else f"https://i.ytimg.com/vi/{v_id}/hqdefault.jpg"

        elif "compactVideoRenderer" in it:
            cvr = it["compactVideoRenderer"]
            v_id = cvr.get("videoId")
            if not v_id or v_id in seen:
                continue
            title = cvr.get("title", {}).get("simpleText") or "".join(
                x.get("text", "") for x in cvr.get("title", {}).get("runs", [])
            )
            channel = cvr.get("shortBylineText", {}).get("runs", [{}])[0].get("text", "YouTube")
            length_str = cvr.get("lengthText", {}).get("simpleText", "")
            thumbs = cvr.get("thumbnail", {}).get("thumbnails", [])
            thumb = thumbs[-1]["url"] if thumbs else f"https://i.ytimg.com/vi/{v_id}/hqdefault.jpg"

        if not v_id or not title:
            continue

        dur_s = _parse_duration_str(length_str)
        if max_duration_s and dur_s is not None and dur_s > max_duration_s:
            continue

        seen.add(v_id)
        tracks.append({
            "id": v_id,
            "title": clean_track_title(title),
            "original_title": title,
            "channel": channel,
            "duration": length_str or "3:30",
            "duration_s": dur_s,
            "thumb": thumb,
            "stream_url": f"/stream/{v_id}",
        })
        if len(tracks) >= limit:
            break

    return tracks


def _apply_artist_spacing(tracks: list[dict[str, Any]], max_consecutive: int = 2) -> list[dict[str, Any]]:
    """
    Implements YouTube Music's artist spacing algorithm.
    Ensures that songs by the same artist/channel don't cluster together more than max_consecutive times.
    """
    if len(tracks) <= 3:
        return tracks

    out: list[dict[str, Any]] = []
    pool = list(tracks)
    artist_run_count: dict[str, int] = {}
    last_artist: Optional[str] = None

    while pool:
        # Find next best track whose artist hasn't exceeded max_consecutive
        picked_idx = None
        for i, t in enumerate(pool):
            art = (t.get("channel") or "Unknown").lower()
            if art == last_artist:
                if artist_run_count.get(art, 0) < max_consecutive:
                    picked_idx = i
                    break
            else:
                picked_idx = i
                break

        if picked_idx is None:
            # If no alternative artist available, take the first one
            picked_idx = 0

        picked = pool.pop(picked_idx)
        art = (picked.get("channel") or "Unknown").lower()
        if art == last_artist:
            artist_run_count[art] = artist_run_count.get(art, 0) + 1
        else:
            last_artist = art
            artist_run_count[art] = 1
        out.append(picked)

    return out


def generate_youtube_station(
    query_or_artist: str,
    *,
    limit: int = 25,
    max_duration_s: int = 720,
) -> dict[str, Any]:
    """
    Takes any search query, artist, genre, or mood.
    Finds the definitive anchor song on YouTube, then launches YouTube's algorithmic Mix Station.
    Returns full playlist with title, seed info, and track list.
    """
    from app.fastsearch import fast_search_youtube_list

    q = (query_or_artist or "").strip()
    if not q:
        return {"name": "YouTube Mix", "seed": None, "tracks": [], "count": 0}

    # 1. Search for top 1 anchor track
    matches = fast_search_youtube_list(q, limit=1)
    if not matches:
        return {"name": f"Mix: {q}", "seed": None, "tracks": [], "count": 0}

    seed = matches[0]
    seed_id = seed["id"]
    seed_title = clean_track_title(seed.get("title") or q)

    # 2. Query YouTube's algorithmic Mix for this seed
    tracks = get_youtube_mix_playlist(
        seed_id,
        limit=limit,
        max_duration_s=max_duration_s,
    )

    # If Mix returned empty, fall back to Related
    if not tracks:
        tracks = get_youtube_related_tracks(
            seed_id,
            limit=limit,
            max_duration_s=max_duration_s,
        )

    # Ensure the seed track is at the beginning if not already present
    if not any(t["id"] == seed_id for t in tracks):
        seed_item = {
            "id": seed_id,
            "title": seed_title,
            "original_title": seed.get("title") or seed_title,
            "channel": seed.get("channel") or "YouTube",
            "duration": seed.get("duration") or "3:30",
            "duration_s": seed.get("duration_s"),
            "thumb": seed.get("thumbnail") or f"https://i.ytimg.com/vi/{seed_id}/hqdefault.jpg",
            "stream_url": f"/stream/{seed_id}",
        }
        tracks.insert(0, seed_item)

    return {
        "name": f"YouTube Mix – {seed_title}",
        "seed": {
            "id": seed_id,
            "title": seed_title,
            "channel": seed.get("channel"),
            "thumb": seed.get("thumbnail"),
        },
        "tracks": tracks[:limit],
        "count": len(tracks[:limit]),
    }


def generate_multi_seed_blend(
    seeds: list[str],
    *,
    limit: int = 25,
    max_duration_s: int = 720,
) -> dict[str, Any]:
    """
    YouTube Music Multi-Artist Blend:
    Takes 2-5 artists or genres, fetches their individual YouTube Mix stations,
    and blends them smoothly in an interleaved round-robin fashion.
    """
    from app.fastsearch import fast_search_youtube_list

    clean_seeds = [s.strip() for s in seeds if s and s.strip()]
    if not clean_seeds:
        return {"name": "Multi-Artist Mix", "tracks": [], "count": 0}

    stations: list[list[dict[str, Any]]] = []
    seed_titles: list[str] = []

    for s in clean_seeds[:4]:
        hits = fast_search_youtube_list(s, limit=1)
        if hits:
            s_id = hits[0]["id"]
            seed_titles.append(hits[0].get("title", s))
            mix = get_youtube_mix_playlist(s_id, limit=limit, max_duration_s=max_duration_s)
            if mix:
                stations.append(mix)

    if not stations:
        return {"name": "Mix: " + ", ".join(clean_seeds), "tracks": [], "count": 0}

    # Interleave stations
    blended: list[dict[str, Any]] = []
    seen: set[str] = set()
    max_len = max(len(st) for st in stations)

    for i in range(max_len):
        for st in stations:
            if i < len(st):
                trk = st[i]
                if trk["id"] not in seen:
                    seen.add(trk["id"])
                    blended.append(trk)
                    if len(blended) >= limit:
                        break
        if len(blended) >= limit:
            break

    # Apply artist separation
    final_tracks = _apply_artist_spacing(blended, max_consecutive=2)[:limit]
    mix_name = f"Mix: {' • '.join(clean_seeds[:3])}"

    return {
        "name": mix_name,
        "tracks": final_tracks,
        "count": len(final_tracks),
    }


def get_autoplay_recommendations(
    current_id: str,
    current_title: str,
    history: list[str] = [],
    count: int = 8,
) -> list[dict[str, Any]]:
    """
    Sub-second AutoPlay recommendation using YouTube's real Mix algorithm.
    Excludes already played tracks / history.
    """
    history_set = {h.lower().strip() for h in history if h}
    if current_title:
        history_set.add(current_title.lower().strip())

    candidates = get_youtube_mix_playlist(current_id, limit=count + 12)
    if not candidates:
        candidates = get_youtube_related_tracks(current_id, limit=count + 12)

    filtered: list[dict[str, Any]] = []
    seen: set[str] = {current_id}

    for c in candidates:
        vid = c.get("id")
        title = (c.get("title") or "").lower().strip()
        if not vid or vid in seen:
            continue
        if title in history_set:
            continue
        seen.add(vid)
        filtered.append(c)
        if len(filtered) >= count:
            break

    return filtered
